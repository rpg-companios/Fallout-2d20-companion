// domain/actionPoints.js
// Общий пул ОД (патч 324, слово владельца) — групповой ресурс 2d20.
//
//   • Пул = 6; больше 6 не бывает (пополнение сверх — срезается);
//   • старт каждой игровой сессии — полный (6);
//   • пополняется успешными проверками: +1 ОД за каждый успех СВЕРХ
//     сложности (крит-кубик даёт 2 успеха — уже считает d20Checks, поэтому
//     «крит успех» вносит свою прибавку сам, слово владельца 324);
//   • тратится на действия (сейчас — «2 ОД: время крафта вдвое», 323).
//
// ПОКА живёт внутри движка (модульная переменная, на сессию) — UI-хранилище
// владелец придумает позже. Пул ГРУППОВОЙ: когда появится мастер и группа,
// восполнять и тратить его смогут все игроки группы — интерфейс функций
// уже это допускает (никакой привязки к персонажу нет).

export const AP_POOL_MAX = 6;

let pool = AP_POOL_MAX;

export const getActionPoints = () => pool;

/** Пополнить пул (проверка сработала). Сверх 6 — срезается. Возвращает пул. */
export const earnActionPoints = (amount) => {
  const gained = Math.max(0, Math.floor(Number(amount) || 0));
  pool = Math.min(AP_POOL_MAX, pool + gained);
  return pool;
};

/**
 * Потратить ОД. Если в пуле меньше — отказ ({ ok: false }), пул не тронут:
 * «больше 6 потратить не выйдет, если только проверки не выдали ОД».
 */
export const spendActionPoints = (amount) => {
  const cost = Math.max(0, Math.floor(Number(amount) || 0));
  if (pool < cost) return { ok: false, pool };
  pool -= cost;
  return { ok: true, pool };
};

/** Новая сессия: пул снова полный (книга — группа начинает с полным пулом). */
export const resetActionPoints = () => {
  pool = AP_POOL_MAX;
  return pool;
};
