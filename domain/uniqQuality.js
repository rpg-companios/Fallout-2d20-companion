// domain/uniqQuality.js
// Уникальные качества (uniq qualities) — навешиваемые модификаторы экипировки.
//
// У качества есть id (механика/учёт), имя (i18n, добавляется к имени
// предмета: «дерзкая» + «форменная одежда» = «дерзкая форменная одежда») и
// зарезервированные эффекты (механика — на будущее, как у модов).
//
// Качество НЕ вшито в предмет: крепится к экземпляру (поле uniqQualities),
// участвует в стек-ключе (uniq_<id>) и в имени. Крепление: данными
// (комплект/запись), механикой (крафт), вручную — всё через одно поле.

/**
 * Чистая композиция имени: [имена качеств..., базовое имя].
 * nameById(id) → имя качества (или пустая строка, если имени нет —
 * качество не влияет на имя).
 */
export const composeNameWithUniqQualities = (baseName, uniqQualityIds = [], nameById = () => '') => {
  const names = (uniqQualityIds || [])
    .map((id) => nameById(id))
    .filter(Boolean);
  return [...names, baseName].filter(Boolean).join(' ');
};
