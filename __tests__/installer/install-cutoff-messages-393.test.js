// ПРИЁМОЧНЫЙ (патч 393): «мой установщик перескочил патч 391, а поставил
// сразу 392» (владелец). Это штатная работа отсечки (391): содержимое
// патчей до ключевого включительно приходит в дерево из истории, поэтому
// 391 не попадает в список «Применено» — но установщик об этом не сказал
// явно, и это законно выглядело как пропуск. Патч добавляет явные
// сообщения: при включении отсечки и в финальном вердикте.
import { describe, expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { execSync } from 'node:child_process';

const script = () => readFileSync('apply-patch.sh', 'utf8');

describe('патч 393: установщик объясняет отсечку словами', () => {
  it('синтаксически цел (bash -n)', () => {
    execSync('bash -n apply-patch.sh');
  });

  it('при включении отсечки сказано, что содержимое до ключа уже в дереве', () => {
    const code = script();
    expect(code).toContain('Содержимое №$BASELINE_NUM и всех патчей до него УЖЕ в дереве');
    expect(code).toContain('по одному они не применяются и в «Применено» не попадут');
  });

  it('в финальном вердикте есть напоминание об отсечке', () => {
    const code = script();
    expect(code).toContain('патчи до неё включительно уже в дереве');
    expect(code).toContain('приведены отсечкой, по одному не проверялись и не применялись');
    // напоминание только в быстром режиме
    expect(code).toContain('if [[ "$FAST_MODE" -eq 1 ]]; then\n    echo\n    echo "Отсечка №$BASELINE_NUM');
  });

  it('usage объясняет, почему патчи до ключа не появляются в «Применено»', () => {
    expect(script()).toContain('по одному они не применяются\nи в списке «Применено» не появятся');
  });
});
