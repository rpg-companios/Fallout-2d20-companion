  // Корневая система 2d20: осложнение не отменяет успех проверки (решение
  // владельца 2026-09-16 вместо правки 258 «порча при осложнении»). Когда
  // успех и осложнение случаются одновременно, наказанием становится время:
  // длительность работы (или негативного эффекта) умножается на этот множитель.
  // 10 минут крафта становятся 20, час — двумя, сутки — двумя. Сами времена —
