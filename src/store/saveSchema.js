// src/store/saveSchema.js
//
// ЕДИНСТВЕННЫЙ источник истины для версии формата сохранения персонажа.
//
// Правило (владелец):
//   - Никогда не менять формат сохранения «на лету» в loadCharacter/serializers.
//   - Любое изменение формата сохранения = новая версия + миграция в migrations.js.
//   - Эта константа импортируется ВСЕМИ местами, которые пишут/читают schemaVersion,
//     чтобы версия не разъезжалась по трём файлам (как было с хардкодом schemaVersion: 1).
//
// Значение: 0 = начальный (неверсированный) формат.
// v1 — разделение эффектов (effect_) и качеств (quality_) в экипировке
//       (см. MIGRATIONS[0] в migrations.js).
// v2 — журнал уже выданных наград за отмеченные навыки.
// v3 — normalize mutually exclusive weapon qualities in legacy saves.
// v4 — damageType из строки в массив (поддержка комбинированного урона).
// v5 — комплект снаряжения без метаданных → заглушка {id: null, name: null}.
// v6 — ориджин «savage» переименован в «tribal».
// v7 — «Опасная бритва» переведена на истинный id (weapon_switchblade) +
//      baseName (вариант предмета; стек = id + моды + имя).
// v8 — формальная одежда/шляпа Председателей получают качество «Элегантная»
//      (uniqQualities) — для сейвов с комплектом из патча 63.
// v9 — числовые статы предметов приведены к объекту { base, modifiers, total }.
// v10 — ориджин «Тень»: полный сброс атрибутов к стартовым (STR/END 6,
//       остальные 4) — лимиты SPECIAL не применялись до исправления формата
//       трейта, сейвы могли содержать значения вне лимитов.
// v11 — починка сейвов, повреждённых багом v9->v10 (attributes превращался
//       из массива в объект): восстановление массива + повторный сброс Тени.
// v12 — «Тень»: полный сброс состояния распределения (attributesSaved/
//       skillsSaved = false, значения навыков к стартовым: tagged 2, иные 0) —
//       очки атрибутов и навыков можно распределить заново; инвентарь не трогается.
// v13 — «Тень»: сейвы хранят трейт целиком со старым форматом modifiers —
//       чиним трейт в сейве (→ канонический attributes) и сбрасываем
//       атрибуты/флаги/навыки к стартовым (инвентарь/уровень не трогаем).
// v14 — «Тень»: старый комплект (default_caps_only) заменяется на NIGHTKIN;
//       флаг nightkinKitPending — предметы выдаются после загрузки.
// v15 — состояние универсальных проверок риска в текущей реальной сцене.
// v16 — одноразовый модификатор сложности для следующей новой категории риска.
// v17 — снять лишние ранги перков сверх catalog maxRanks; сейв перка — {id, rank}.
// v18 — id перков: triggerRush→scrounger, slacker→dodger, bullRush→painTrain.
// v19 — «худой» сейв: предметы хранят только состояние экземпляра, имя/цену/
//       вес/статы/моды достаёт resolveItem по id (domain/saveSlimming.js).
// v20 — «худой» сейв для слотов робота: конечность, слои защиты и оружие
//       хранятся id (+ список id модов), характеристики восстанавливаются из
//       каталогов. Ужимка — на экспорте (slimRobotSlots), разворот — на импорте
//       (restoreSaveData). Само хранилище пока пишет «толстые» объекты: смена
//       физического формата требует слоя доступа к слоту (риск Р1) и идёт
//       отдельным шагом. Миграция — только бамп версии, идемпотентна.
// v19 — предметы в сейве хранят только состояние экземпляра (id/quantity/
//       equipped/locked/appliedMods/charges/…), а имя/цену/вес/статы/моды
//       достаёт resolveItem по id (см. domain/saveSlimming.js). Обратная
//       совместимость: старые «жирные» сейвы (v18 и ниже) при загрузке
//       восстанавливаются (restoreSaveData), а при сохранении становятся
//       «худыми» (slimSaveData). Миграция v18→v19 — только бамп версии.
// v21 — «Заводская обшивка» убрана из каталога (в книге её нет, есть только
//       стандартная): ссылки robot_plating_factory_* в слотах робота и в
//       инвентаре переименованы в robot_plating_standard_* (миграция
//       migrateRobotPlatingIds в migrations.js).
// v22 — навесы (arm attachments) — оружие, крепящееся к руке: слоты, где
//       навес стоял вместо руки, получают стандартную руку плана тела,
//       навес пересаживается в ладонь (миграция migrateRobotArmAttachments).
