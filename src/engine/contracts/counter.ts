// КОНТРАКТ ВЫВОДИМОСТИ — счётчики (МК-1, патч 281).
//
// Счётчик — расходуемый ресурс: очки удачи, мана, заряды. Правило устава
// (§4): spend возвращает исход, отказ не трогает баланс («нельзя купить на
// больше, чем есть»). Потолок счётчика может быть числом или ссылкой на
// производное — тогда при пересчёте потолка движок подрезает current сверху
// (семантика.characterStore: current = min(current, newMax)).

/** Исход расхода: успех молчит, отказ объясняет причину и НЕ меняет баланс. */
export type SpendOutcome = { ok: true } | { ok: false; reason: string };

/** Объявление счётчика. */
export interface CounterDefinition {
  /** Полный id с префиксом сеттинга ('fallout.luckPoints'). */
  id: string;
  /** Потолок: число ИЛИ id производного ('fallout.maxHealth'). */
  max: number | string;
  /** Человекочитаемое имя. */
  label: string;
  /** Минимум, ниже которого счётчик не опускается (по умолчанию 0). */
  min?: number;
}
