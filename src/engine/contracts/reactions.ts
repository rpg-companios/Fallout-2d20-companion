// КОНТРАКТ ВЫВОДИМОСТИ — реакции (МК-1, патч 281).
//
// Реакция — «правило при изменении»: после каскада движок зовёт подписанные
// реакции, если изменился хотя бы один из watch-параметров. Карта каскада
// (§6) показала: настоящих реакций в программе единицы (зажим HP, подмена
// атрибута силовой бронёй, пороги выживания) — поэтому реактивное ядро
// менять не нужно, достаточно договора.

/** Реакция на изменение параметров. */
export interface ReactionDefinition {
  /** Полный id с префиксом сеттинга. */
  id: string;
  /** Что слушаем: непустой список полных id параметров/производных. */
  watch: readonly string[];
  /**
   * Вызывается после каскада, если хоть один watch изменился.
   * Возвращает список модификаторов/действий для следующего прохода каскада
   * (v1: пусто — реакция сама пишет через операции движка; фиксация после МК-3).
   */
  on: (changed: readonly string[], ctx: unknown) => void;
  /** Что делает — для трассировки. */
  description: string;
}

/** Какие watch-параметры изменились между двумя снимками значений. */
export const changedParams = (
  watch: readonly string[],
  before: Readonly<Record<string, number>>,
  after: Readonly<Record<string, number>>,
): readonly string[] =>
  watch.filter((id) => before[id] !== after[id]);
