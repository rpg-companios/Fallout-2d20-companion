// КОНТРАКТ ВЫВОДИМОСТИ — производные значения (МК-1, патчи 281–283).
//
// Производное — значение, которое ВЫЧИСЛЯЕТСЯ из параметров, а не хранится.
// Ключевой разворот серии (карта каскада, docs/architecture/cascade-map.md):
// сегодня итоги лежат в сторе и пересчитываются 24 ручными вызовами; после
// МК-3 производные будут вычисляться каскадом реестра при любом изменении
// входа. Контракт ниже — то, что сеттинг объявляет, а движок исполняет.

import type { DerivationContext, ModifierPhase, ParameterModifier, RoundingMode } from './parameter';

// Контекст вычислений живёт в parameter.ts (общий для условий и формул);
// реэкспортируем, чтобы потребитель брал всё из бочки contracts.
export type { DerivationContext } from './parameter';

/** Объявление производного значения. */
export interface DerivedDefinition {
  /** Полный id с префиксом сеттинга ('fallout.maxHealth'). */
  id: string;
  /** Вид производного — движок различает режимы пересчёта (v1: 'derived'). */
  kind: 'derived' | 'max' | 'rankCeiling';
  /** Параметры-входы: непустой список полных id. */
  deps: readonly string[];
  /** Чистая функция: контекст → число (БАЗА производного). Без побочных эффектов. */
  compute: (ctx: DerivationContext) => number;
  /** Что это и откуда берётся — для трассировки и ошибок. */
  description: string;
  /** Конвейер модификаторов поверх базы: фазы в порядке исполнения.
   *  Отсутствует — дефолт ['add', 'percent', 'mult']. Порядок объявляет
   *  правило сеттинга (слово владельца: «как в правилах напишут»). */
  modifierPhases?: readonly ModifierPhase[];
  /** Режим округления итога — диктует сеттинг (патч 284). По умолчанию 'math'. */
  rounding?: RoundingMode;
}

/** Модификатор, привязанный к параметру-цели (для реестра). */
export interface TargetedModifier extends ParameterModifier {
  /** Параметр, к которому применяется модификатор. */
  paramId: string;
}
